#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""server/scripts/import_ml_r_contact.py — SHIELD Stage 2, Part E, task #4.

One-off script: reads the `ML_R_CONTACT` JS array literal out of
index.html (contact-resistance baseline measurements, historically kept
client-side only) and PRINTS the `INSERT INTO maintenance_events ...`
statements that would import them — it NEVER connects to a database or
executes anything. Review the printed SQL (and especially the flagged
warnings) before running any of it yourself.

One ML_R_CONTACT entry (one trafo, one date, 3 phase readings R/S/T, one
test current) becomes THREE maintenance_events rows (event_type=
'resistance_test', phase='R'|'S'|'T', resistance_uohm=that phase's value).

Flags printed above the affected rows (NOT auto-corrected, NOT silently
skipped -- this script only prints for your review per the task brief):
  - DUPLICATE: two entries for the SAME trafo with IDENTICAL R readings on
    different dates (a copy-paste error is far more likely than the exact
    same three-phase resistance being measured twice).
  - OUTLIER: an entry whose mean resistance is far (default: >3x or <1/3)
    from the median of that trafo's OTHER entries -- flags exactly the
    pattern you described (Trafo 2's 2024 readings, 10-29 µΩ, sitting far
    below both its 2022 and 2026 readings, ~115-165 µΎΩ).

Usage:
    python3 server/scripts/import_ml_r_contact.py [path/to/index.html]
    (default path: ../../index.html relative to this script)
"""

from __future__ import annotations

import re
import sys
from pathlib import Path
from statistics import median
from typing import Any

# TODO(verifikasi): ambang deteksi outlier murni heuristik (rasio magnitude),
# bukan hasil analisis statistik formal -- cukup untuk menangkap pola yang
# diminta (beda >3x antar entri trafo yang sama), tinjau manual tetap wajib.
OUTLIER_HIGH_RATIO = 3.0
OUTLIER_LOW_RATIO = 1.0 / 3.0

_ENTRY_RE = re.compile(
    r"\{date:'(?P<date>[^']+)',trafo:(?P<trafo>\d+),"
    r"R:\[(?P<r>[^\]]+)\]\s*,\s*I:(?P<i>[0-9.]+),\s*source:'(?P<source>[^']+)'\}"
)


def extract_ml_r_contact(html_text: str) -> list[dict[str, Any]]:
    match = re.search(r"let\s+ML_R_CONTACT\s*=\s*\[(.*?)\];", html_text, re.S)
    if not match:
        raise ValueError("ML_R_CONTACT array literal not found in the given file")

    entries = []
    for m in _ENTRY_RE.finditer(match.group(1)):
        r_values = [float(v.strip()) for v in m.group("r").split(",")]
        if len(r_values) != 3:
            raise ValueError(f"Expected exactly 3 R values, got {len(r_values)}: {m.group(0)}")
        entries.append({
            "date": m.group("date"),
            "trafo": int(m.group("trafo")),
            "r": r_values,  # [R-phase, S-phase, T-phase], µΩ
            "i": float(m.group("i")),
            "source": m.group("source"),
        })
    return entries


def find_duplicates(entries: list[dict[str, Any]]) -> list[tuple[dict[str, Any], dict[str, Any]]]:
    """Pairs of entries for the SAME trafo with IDENTICAL R readings on
    DIFFERENT dates."""
    duplicates = []
    for i, a in enumerate(entries):
        for b in entries[i + 1:]:
            if a["trafo"] == b["trafo"] and a["r"] == b["r"] and a["date"] != b["date"]:
                duplicates.append((a, b))
    return duplicates


def find_outliers(entries: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Entries whose mean resistance is far from the median of that same
    trafo's OTHER entries (ratio-based, see OUTLIER_*_RATIO)."""
    by_trafo: dict[int, list[dict[str, Any]]] = {}
    for e in entries:
        by_trafo.setdefault(e["trafo"], []).append(e)

    outliers = []
    for trafo, group in by_trafo.items():
        if len(group) < 2:
            continue
        for entry in group:
            others = [sum(e["r"]) / 3.0 for e in group if e is not entry]
            if not others:
                continue
            entry_mean = sum(entry["r"]) / 3.0
            others_median = median(others)
            if others_median <= 0:
                continue
            ratio = entry_mean / others_median
            if ratio >= OUTLIER_HIGH_RATIO or ratio <= OUTLIER_LOW_RATIO:
                outliers.append({**entry, "ratio_to_others_median": ratio, "others_median_uohm": others_median})
    return outliers


def generate_inserts(entries: list[dict[str, Any]], duplicates, outliers) -> str:
    duplicate_marks = set()
    for a, b in duplicates:
        duplicate_marks.add((a["date"], a["trafo"]))
        duplicate_marks.add((b["date"], b["trafo"]))
    outlier_marks = {(o["date"], o["trafo"]): o for o in outliers}

    lines: list[str] = []
    lines.append("-- Generated by server/scripts/import_ml_r_contact.py — REVIEW BEFORE RUNNING.")
    lines.append("-- NOT executed by this script. Each ML_R_CONTACT entry becomes 3 rows (phase R/S/T).")
    lines.append("-- resets_baseline defaults to TRUE for every row (a resistance_test measurement")
    lines.append("-- is treated as establishing a new baseline) EXCEPT where flagged below — for")
    lines.append("-- flagged rows, consider changing resets_baseline to FALSE before running, since")
    lines.append("-- a suspect/erroneous measurement should probably not reset the aging chronology.")
    lines.append("BEGIN;")
    lines.append("")

    phases = ("R", "S", "T")
    for entry in entries:
        key = (entry["date"], entry["trafo"])
        flags = []
        if key in duplicate_marks:
            flags.append("DUPLICATE: identical R readings also appear on another date for this trafo")
        if key in outlier_marks:
            o = outlier_marks[key]
            flags.append(
                f"OUTLIER: mean {sum(entry['r'])/3.0:.1f} µΩ is {o['ratio_to_others_median']:.1f}x "
                f"this trafo's other-entries median ({o['others_median_uohm']:.1f} µΩ)"
            )
        if flags:
            lines.append(f"-- *** REVIEW REQUIRED — trafo {entry['trafo']} @ {entry['date']} ***")
            for f in flags:
                lines.append(f"--   {f}")

        for phase, r_value in zip(phases, entry["r"]):
            notes = f"Imported from index.html ML_R_CONTACT (source={entry['source']})"
            lines.append(
                "INSERT INTO maintenance_events "
                "(trafo, phase, event_type, event_ts, resistance_uohm, test_current_a, notes, "
                "resets_baseline, created_by) VALUES ("
                f"'{entry['trafo']}', '{phase}', 'resistance_test', "
                f"'{entry['date']}T00:00:00+00:00', {r_value}, {entry['i']}, "
                f"'{notes}', TRUE, 'import_ml_r_contact.py');"
            )
        lines.append("")

    lines.append("COMMIT;")
    return "\n".join(lines)


def main() -> None:
    default_path = Path(__file__).resolve().parent.parent.parent / "index.html"
    html_path = Path(sys.argv[1]) if len(sys.argv) > 1 else default_path

    html_text = html_path.read_text(encoding="utf-8")
    entries = extract_ml_r_contact(html_text)
    duplicates = find_duplicates(entries)
    outliers = find_outliers(entries)

    print(f"-- Source: {html_path}")
    print(f"-- {len(entries)} ML_R_CONTACT entries found -> {len(entries) * 3} INSERT statements generated.")
    print(f"-- {len(duplicates)} duplicate pair(s) flagged, {len(outliers)} outlier entry/entries flagged.")
    print()
    print(generate_inserts(entries, duplicates, outliers))

    if duplicates or outliers:
        print()
        print("-- ===== SUMMARY OF FLAGS (for your review, nothing auto-corrected) =====", file=sys.stderr)
        for a, b in duplicates:
            print(f"--   DUPLICATE: trafo {a['trafo']} on {a['date']} and {b['date']} have identical R={a['r']}", file=sys.stderr)
        for o in outliers:
            print(
                f"--   OUTLIER: trafo {o['trafo']} on {o['date']} mean={sum(o['r'])/3.0:.1f} µΩ "
                f"vs other-entries median={o['others_median_uohm']:.1f} µΩ (ratio {o['ratio_to_others_median']:.1f}x)",
                file=sys.stderr,
            )


if __name__ == "__main__":
    main()
